export function downloadDataUrl(dataUrl, filename) {
  const a = document.createElement('a');
  a.href = dataUrl;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
}

export function downloadText(text, filename, type = 'text/plain') {
  const url = URL.createObjectURL(new Blob([text], { type }));
  downloadDataUrl(url, filename);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function readFileAsDataUrl(file) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(reader.result);
    reader.onerror = () => reject(reader.error);
    reader.readAsDataURL(file);
  });
}

/** Plain-text resume generated from a candidate snapshot (used for demo downloads). */
export function buildResumeText(c) {
  const line = '-'.repeat(48);
  return [
    c.name.toUpperCase(),
    c.headline,
    [c.email, c.phone, c.location].filter(Boolean).join(' | '),
    line,
    'SUMMARY',
    c.summary || '—',
    '',
    'EXPERIENCE',
    `${c.experienceYears ?? 0}+ years of professional experience`,
    '',
    'SKILLS',
    (c.skills || []).join(', ') || '—',
    '',
    'EDUCATION',
    c.education || '—',
    line,
    'Generated by HireFlow (demo)',
  ].join('\n');
}
